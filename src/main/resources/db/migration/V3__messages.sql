-- Messages des salons, réactions et suivi de lecture.

CREATE TABLE messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id  BIGINT        NOT NULL REFERENCES channels (id) ON DELETE CASCADE,
    author_id   BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    content     VARCHAR(4000) NOT NULL,
    -- Message auquel on répond (NULL si le message d'origine a été supprimé).
    reply_to_id BIGINT REFERENCES messages (id) ON DELETE SET NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    edited_at   TIMESTAMP WITH TIME ZONE
);

-- L'historique se lit salon par salon, du plus récent au plus ancien.
CREATE INDEX idx_messages_channel_id ON messages (channel_id, id);

CREATE TABLE message_reactions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT      NOT NULL REFERENCES messages (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    emoji      VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_message_reactions UNIQUE (message_id, user_id, emoji)
);

CREATE INDEX idx_message_reactions_message ON message_reactions (message_id);

-- Dernier message lu par un utilisateur dans un salon (pour les non-lus).
CREATE TABLE channel_reads (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    channel_id           BIGINT NOT NULL REFERENCES channels (id) ON DELETE CASCADE,
    last_read_message_id BIGINT NOT NULL,
    CONSTRAINT uk_channel_reads UNIQUE (user_id, channel_id)
);
