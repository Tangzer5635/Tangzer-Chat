-- Serveurs (communautés), membres, salons et invitations.

CREATE TABLE servers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50)  NOT NULL,
    description VARCHAR(300),
    -- Emoji affiché comme icône (sinon le front affiche les initiales).
    icon        VARCHAR(16),
    color       VARCHAR(7)   NOT NULL,
    is_public   BOOLEAN      NOT NULL DEFAULT FALSE,
    -- Serveur rejoint automatiquement par chaque nouvel inscrit.
    is_default  BOOLEAN      NOT NULL DEFAULT FALSE,
    owner_id    BIGINT       NOT NULL REFERENCES users (id),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE memberships (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id BIGINT      NOT NULL REFERENCES servers (id) ON DELETE CASCADE,
    user_id   BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role      VARCHAR(16) NOT NULL,
    joined_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_memberships_server_user UNIQUE (server_id, user_id)
);

CREATE INDEX idx_memberships_user ON memberships (user_id);

CREATE TABLE channels (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id  BIGINT      NOT NULL REFERENCES servers (id) ON DELETE CASCADE,
    name       VARCHAR(32) NOT NULL,
    topic      VARCHAR(200),
    type       VARCHAR(16) NOT NULL,
    position   INT         NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_channels_server ON channels (server_id);

CREATE TABLE invites (
    code       VARCHAR(16) PRIMARY KEY,
    server_id  BIGINT NOT NULL REFERENCES servers (id) ON DELETE CASCADE,
    created_by BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    -- NULL = jamais d'expiration / utilisations illimitées.
    expires_at TIMESTAMP WITH TIME ZONE,
    max_uses   INT,
    uses       INT NOT NULL DEFAULT 0
);

CREATE INDEX idx_invites_server ON invites (server_id);
